/**
 * The system chain, in cost order.
 *
 * Concatenating the bands is the ordering contract made explicit: the sequence
 * is the order a request walks, and every band boundary is a real cost boundary.
 */
export const DEFAULT_FALLBACK_ORDERED_IDS: readonly string[] = [
  ...DEFAULT_FALLBACK_FREE_IDS,
  ...DEFAULT_FALLBACK_SUBSCRIPTION_IDS,
  ...DEFAULT_FALLBACK_PAID_IDS
] as const;

export function buildDefaultFallbackModelIds(): string[] {
  return [...DEFAULT_FALLBACK_ORDERED_IDS];
}

export function buildDefaultFallbackModelsText(): string {
  return buildDefaultFallbackModelIds().join('\n');
}

