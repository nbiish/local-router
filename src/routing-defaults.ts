/**
 * Default system fallback chains and preset fallback routes.
 *
 * The auto-router system was removed (2026-08-23): routing is either a
 * direct provider model or an explicit user-configured fallback chain.
 *
 * Ordering contract (2026-11-09): cost-first, then capability. Free tier, then
 * subscription/OAuth capacity that is already paid for, then metered paid models
 * cheapest-first. Inside a band the larger context window wins, with reasoning
 * depth, vision and caching as tiebreaks. `src/fallback-topology.ts` implements
 * it and `npm run verify:fallback` checks a live chain against it.
 *
 * The seed below is generated from measured facts, not hand-written: every
 * chat-capable provider with a configured key/OAuth appears at least once, so a
 * single provider failure cannot remove a subscription from the chain. Rebuild it
 * with `node scripts/seed-fallback-chain.mjs` after adding a provider or key.
 *
 * `typesafe` and the local `ollama` backend are deliberately absent: TypeSafe
 * serves typed decisions and is reached through `/api/alpha/decisions`, and a
 * loopback backend is not a fallback target.
 */

